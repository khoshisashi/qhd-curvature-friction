"""Table II and the statements of Secs. V-B and V-C on the representation gap.

Thirty covariance targets outside the factor family at d = 6 are fitted by four families: three
factors as drawn, the same loadings after a QR orthogonalisation, five factors, and three factors
with a variable diagonal. The gap of a family on a target is the minimum of F over its design box
minus the minimum over the positive semidefinite cone, in units of the family's own range of F.

  python -m experiments.table2_representation_gap        thirty targets, about 8 minutes on one core
  python -m experiments.table2_representation_gap 3      the first three targets only, without comparison

The full run writes results/representation_gap.json, which the script of Fig. 3 reads.
"""
import itertools
import json
import pathlib
import sys
import time

import numpy as np
from scipy.optimize import minimize

from core.landscape import HORIZON, RATE, WIDTH
from core.report import Published, header

D, N_SP = 6, 2
N_TARGETS = 30
N_SCAN = 4000          # random points of the scan, in addition to the corners of the box
N_REFINE = 3           # local refinements, from the best points of the scan
N_SCAN_DIAG = 3000     # the same two numbers for the nine-dimensional box of the variable diagonal
N_REFINE_DIAG = 2
DIAG = (0.01, 0.04)    # range of the diagonal entries
FAMILIES = {           # name: label of Table II
    "M3_drawn": "M=3, as drawn",
    "M3_orth": "M=3, orthogonal",
    "M5_drawn": "M=5, as drawn",
    "M3_vardiag": "M=3, variable diag.",
}
PRINTED = {            # Table II: min, median, max
    "M3_drawn": (0.196, 0.452, 1.095),
    "M3_orth": (0.163, 0.352, 0.744),
    "M5_drawn": (0.087, 0.228, 0.552),
    "M3_vardiag": (0.089, 0.224, 0.499),
}
OUT = pathlib.Path(__file__).resolve().parents[1] / "results" / "representation_gap.json"

nx = 2 ** N_SP
k1 = 2 * np.pi * np.fft.fftfreq(nx, d=WIDTH / nx)
x1 = (np.arange(nx) - nx // 2) * WIDTH / nx
K = np.stack(np.meshgrid(*[k1] * D, indexing="ij")).reshape(D, -1)
X = np.stack(np.meshgrid(*[x1] * D, indexing="ij")).reshape(D, -1)
u0 = (np.exp(-(X ** 2).sum(0) / (2 * 0.8 ** 2))
      - 0.6 * np.exp(-((X - 0.9) ** 2).sum(0) / (2 * 0.8 ** 2)))
u0 /= np.linalg.norm(u0)
WEIGHT = np.abs(np.fft.fftn(u0.reshape([nx] * D)).ravel() / np.sqrt(u0.size)) ** 2
KK = (K[:, None, :] * K[None, :, :]).reshape(D * D, -1)   # k_i k_j for every pair
DRIFT0 = RATE * K.sum(0)


def propagator(S):
    """exp(-a(k) T), clamped to the unit disc, for covariance matrices of shape (n, d, d)."""
    n = S.shape[0]
    q = 0.5 * (S.reshape(n, D * D) @ KK)
    drift = DRIFT0[None, :] - 0.5 * (np.diagonal(S, axis1=1, axis2=2) @ K)
    v = np.exp(-(RATE + q - 1j * drift) * HORIZON)
    mag = np.abs(v)
    return np.where(mag > 1.0, v / mag, v)


def make_objective(S_target, chunk=4000):
    """F for a batch of covariance matrices, the target generated by the same forward map."""
    target = propagator(S_target[None])[0]

    def F(S):
        out = np.empty(S.shape[0])
        for c0 in range(0, S.shape[0], chunk):
            part = slice(c0, c0 + chunk)
            out[part] = (WEIGHT[None] * np.abs(propagator(S[part]) - target[None]) ** 2).sum(1)
        return out

    return F


def frame(n_factors, seed, orthogonal=False):
    """Diagonal and loadings of a factor family, the diagonal drawn first."""
    rng = np.random.default_rng(seed)
    delta = rng.uniform(*DIAG, D)
    V = rng.normal(size=(D, n_factors)) / np.sqrt(D) * 0.55
    if orthogonal:
        Q, _ = np.linalg.qr(V)
        V = Q * np.linalg.norm(V, axis=0)
    return V, delta


def fixed_diagonal(V, delta):
    """Family diag(delta) + sum_mu xi_mu v_mu v_mu^T on the box [0, 1]^M."""
    M = V.shape[1]

    def sigma(z):
        xi = np.clip(np.atleast_2d(z), 0.0, 1.0)
        return np.einsum("nm,im,jm->nij", xi, V, V) + np.diag(delta)[None]

    return sigma, np.zeros(M), np.ones(M)


def variable_diagonal(V):
    """Family sum_mu xi_mu v_mu v_mu^T + diag(zeta) on the box [0, 1]^M x DIAG^d."""
    M = V.shape[1]
    idx = np.arange(D)

    def sigma(z):
        z = np.atleast_2d(z)
        S = np.einsum("nm,im,jm->nij", np.clip(z[:, :M], 0.0, 1.0), V, V)
        S[:, idx, idx] += np.clip(z[:, M:], *DIAG)
        return S

    return sigma, np.r_[np.zeros(M), np.full(D, DIAG[0])], np.r_[np.ones(M), np.full(D, DIAG[1])]


def min_over_box(F, sigma, lower, upper, seed):
    """Minimum and range of F over a box: the corners and N_SCAN random points, then Nelder-Mead
    from the N_REFINE best of them. The range is that of the scan."""
    rng = np.random.default_rng(seed)
    corners = np.array(list(itertools.product(*zip(lower, upper))))
    points = np.concatenate([corners, lower + (upper - lower) * rng.uniform(0, 1, size=(N_SCAN, len(lower)))])
    values = F(sigma(points))
    order = np.argsort(values)
    best = float(values[order[0]])
    span = float(values.max()) - best
    for i in order[:N_REFINE]:
        opt = minimize(lambda z: float(F(sigma(z[None]))[0]), points[i], method="Nelder-Mead",
                       options=dict(xatol=1e-8, fatol=1e-18, maxiter=4000))
        best = min(best, float(opt.fun))
    return best, max(span, 1e-300)


def min_over_diagonal_box(F, sigma, lower, upper, seed):
    """The same for the box of the variable diagonal, in coordinates scaled to the unit cube: the
    corners and N_SCAN_DIAG random points, then bounded quasi-Newton descent from the
    N_REFINE_DIAG best of them. The range runs from the largest value of the scan to the refined
    minimum."""
    rng = np.random.default_rng(seed)
    n = len(lower)
    width = upper - lower
    corners = np.array(list(itertools.product([0.0, 1.0], repeat=n)))
    points = np.concatenate([corners, rng.uniform(0, 1, size=(N_SCAN_DIAG, n))])
    values = F(sigma(lower + width * points))
    order = np.argsort(values)
    best = float(values[order[0]])

    def scaled(u):
        return float(F(sigma((lower + width * np.clip(u, 0.0, 1.0))[None]))[0])

    for i in order[:N_REFINE_DIAG]:
        opt = minimize(scaled, points[i], method="L-BFGS-B", bounds=[(0, 1)] * n, options=dict(maxiter=500))
        best = min(best, float(opt.fun))
    return best, float(values.max()) - best


def min_over_cone(F, S_target, seed, jitter=0.02):
    """Minimum of F over the positive semidefinite cone, through a Cholesky factor."""
    rng = np.random.default_rng(seed)
    tril = np.tril_indices(D)

    def covariance(p):
        L = np.zeros((D, D))
        L[tril] = p
        return L @ L.T

    p0 = np.linalg.cholesky(S_target + 1e-9 * np.eye(D))[tril]
    p0 = p0 + rng.normal(size=p0.size) * jitter
    opt = minimize(lambda p: float(F(covariance(p)[None])[0]), p0, method="L-BFGS-B",
                   options=dict(maxiter=600))
    return float(opt.fun)


def measure(n_targets):
    names = list(FAMILIES) + ["M3_target_diag"]
    raw = {name: [] for name in names}
    span = {name: [] for name in names}
    cone = []
    rng = np.random.default_rng(2)
    print(f"{'target':>6} " + " ".join(f"{name:>10}" for name in FAMILIES) + f" {'cone':>10} {'s':>6}")
    for t in range(n_targets):
        t0 = time.time()
        B = rng.normal(size=(D, D)) / np.sqrt(D) * 0.35
        diag_target = rng.uniform(*DIAG, D)
        S_target = B @ B.T + np.diag(diag_target)
        F = make_objective(S_target)
        cone.append(min_over_cone(F, S_target, seed=t))
        V3, delta3 = frame(3, 11 + t)
        boxes = {
            "M3_drawn": fixed_diagonal(V3, delta3),
            "M5_drawn": fixed_diagonal(*frame(5, 11 + t)),
            "M3_orth": fixed_diagonal(*frame(3, 11 + t, orthogonal=True)),
            "M3_vardiag": variable_diagonal(V3),
            "M3_target_diag": fixed_diagonal(V3, diag_target),
        }
        for name, box in boxes.items():
            search = min_over_diagonal_box if name == "M3_vardiag" else min_over_box
            best, width = search(F, *box, seed=100 + t)
            raw[name].append(best - cone[-1])
            span[name].append(width)
        print(f"{t + 1:>6} " + " ".join(f"{raw[name][-1] / span[name][-1]:>10.4f}" for name in FAMILIES)
              + f" {cone[-1]:>10.2e} {time.time() - t0:>6.1f}", flush=True)
    arrays = lambda table: {name: np.array(v) for name, v in table.items()}
    return arrays(raw), arrays(span), np.array(cone)


def main():
    n_targets = int(sys.argv[1]) if len(sys.argv) > 1 else N_TARGETS
    header("Table II. Representation gap over thirty targets at d = 6")
    print(f"d = {D}, N_x = {nx}, modes = {K.shape[1]}, scan of {N_SCAN} random points and the corners with "
          f"{N_REFINE} refinements, {N_SCAN_DIAG} and {N_REFINE_DIAG} for the variable diagonal")
    raw, span, cone = measure(n_targets)
    gap = {name: raw[name] / span[name] for name in raw}

    print()
    print(f"{'Table II':<22}{'min':>8}{'25%':>8}{'median':>8}{'75%':>8}{'max':>8}")
    for name, label in FAMILIES.items():
        g = gap[name]
        print(f"{label:<22}{g.min():>8.3f}{np.percentile(g, 25):>8.3f}{np.median(g):>8.3f}"
              f"{np.percentile(g, 75):>8.3f}{g.max():>8.3f}")
    print(f"cone minimum, zero by construction: between {cone.min():.1e} and {cone.max():.1e}")

    base, base_raw, base_span = gap["M3_drawn"], raw["M3_drawn"], span["M3_drawn"]
    paired = {}
    print()
    print("paired with M=3 as drawn, on the same targets")
    print(f"{'':<22}{'gap lower':>10}{'median change':>15}{'raw lower':>11}{'median raw ratio':>18}"
          f"{'median range ratio':>20}")
    for name in ("M3_orth", "M5_drawn", "M3_vardiag", "M3_target_diag"):
        ratio = raw[name] / base_raw
        paired[name] = dict(lower=int((gap[name] < base).sum()), change=float(np.median(gap[name] - base)),
                            raw_lower=int((ratio < 1).sum()), raw_ratio=float(np.median(ratio)),
                            range_ratio=float(np.median(span[name] / base_span)))
        p = paired[name]
        label = FAMILIES.get(name, "M=3, target's diagonal")
        print(f"{label:<22}{p['lower']:>7} of {n_targets}{p['change']:>15.3f}"
              f"{p['raw_lower']:>8} of {n_targets}{p['raw_ratio']:>18.3f}{p['range_ratio']:>20.3f}")
    disagree = sum(int(((gap[name] < base) != (raw[name] < base_raw)).sum())
                   for name in ("M3_orth", "M5_drawn"))
    print(f"normalised and raw measure disagree on {disagree} of the {2 * n_targets} comparisons with "
          f"the orthogonal and the five-factor family")
    print(f"targets on which the gap of M=3 as drawn exceeds one: {int((base > 1).sum())}")
    m = 5
    print(f"design qubits at m = {m}: variable-diagonal M=3 {m * (3 + D)}, fixed-diagonal M=5 {m * 5}, "
          f"covariance entries {m * D * (D + 1) // 2}")

    if n_targets != N_TARGETS:
        print(f"\n{n_targets} targets only: no comparison with the paper, and nothing is written")
        return 0

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(dict(
        d=D, nx=nx, modes=int(K.shape[1]), n_targets=N_TARGETS, n_scan=N_SCAN, n_refine=N_REFINE,
        n_scan_diagonal=N_SCAN_DIAG, n_refine_diagonal=N_REFINE_DIAG,
        families={name: dict(label=FAMILIES.get(name, "M=3, diagonal of the target"), gap=gap[name].tolist(),
                             raw_gap=raw[name].tolist(), range=span[name].tolist()) for name in raw},
        cone_residual=cone.tolist()), indent=1) + "\n")
    print(f"\nwrote results/{OUT.name}")

    pub = Published()
    for name, label in FAMILIES.items():
        g = gap[name]
        computed = (g.min(), np.median(g), g.max())
        for tag, value, printed in zip(("min", "median", "max"), computed, PRINTED[name]):
            pub.add(f"Table II {label} {tag}", value, printed, 3)
    pub.add("Sec. V-B: five factors lower the gap in (of 30)", paired["M5_drawn"]["lower"], 26, 0)
    pub.add("Sec. V-B: orthogonal directions lower the gap in", paired["M3_orth"]["lower"], 28, 0)
    pub.add("Sec. V-B: median lowering by five factors", -paired["M5_drawn"]["change"], 0.238, 3)
    pub.add("Sec. V-B: median lowering by orthogonal directions", -paired["M3_orth"]["change"], 0.079, 3)
    pub.add("Sec. V-B: raw residual lower with five factors in", paired["M5_drawn"]["raw_lower"], 25, 0)
    pub.add("Sec. V-B: raw residual lower with orthogonal directions in",
            paired["M3_orth"]["raw_lower"], 28, 0)
    pub.add("Sec. V-B: raw residual lower with a variable diagonal in",
            paired["M3_vardiag"]["raw_lower"], 30, 0)
    pub.add("Sec. V-B: median raw ratio, variable diagonal", paired["M3_vardiag"]["raw_ratio"], 0.811, 3)
    pub.add("Sec. V-B: median raw ratio, five factors", paired["M5_drawn"]["raw_ratio"], 0.656, 3)
    pub.add("Sec. V-C: median raw ratio, orthogonal directions", paired["M3_orth"]["raw_ratio"], 0.870, 3)
    pub.add("Sec. V-B: range ratio, orthogonal", paired["M3_orth"]["range_ratio"], 1.06, 2)
    pub.add("Sec. V-B: range ratio, five factors", paired["M5_drawn"]["range_ratio"], 1.21, 2)
    pub.add("Sec. V-B: comparisons on which the two measures disagree", disagree, 1, 0)
    pub.add("Sec. V-B: targets with a gap above one", int((base > 1).sum()), 1, 0)
    pub.add("Sec. V-B: cone minimum, smallest, in 1e-9", cone.min() * 1e9, 1.0, 1)
    pub.add("Sec. V-B: cone minimum, largest, in 1e-9", cone.max() * 1e9, 7.3, 1)
    return 1 if pub.report() else 0


if __name__ == "__main__":
    sys.exit(main())
